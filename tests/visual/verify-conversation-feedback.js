async (page) => {
  const base = 'http://127.0.0.1:1435/tests/visual/conversation-feedback.html'
  const capture = name => page.screenshot({ path: `output/playwright/${name}.png` })
  const assert = (condition, message) => { if (!condition) throw new Error(message) }
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto(base)
  await page.getByRole('button', { name: '准', exact: true }).click()
  assert(await page.getByRole('button', { name: '准', exact: true }).getAttribute('aria-pressed') === 'true', 'Vote not selected')
  assert(await page.getByText('已确认准', { exact: true }).count() === 0, 'Redundant confirmation line')
  await capture('01-route-accurate')
  await page.getByRole('button', { name: '不准', exact: true }).click()
  await page.getByRole('combobox', { name: '实际工作区' }).selectOption('/workspace/seatalk-bot')
  await page.getByRole('button', { name: '保存反馈' }).click()
  assert(await page.getByRole('button', { name: '不准', exact: true }).getAttribute('aria-pressed') === 'true', 'Correction not selected')
  await capture('01-route-inaccurate')
  await page.getByRole('textbox', { name: '给 Codex 发送消息' }).fill('可以，继续检查现有 Bot 和会话接入能力。')
  await page.getByRole('button', { name: '发送消息', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('textarea[placeholder="给 Codex 发送消息"]').value === '')
  assert(await page.getByText('工作区路由', { exact: true }).count() === 0, 'Route card still visible after follow-up')
  await capture('02-second-message-cleared')
  await page.getByRole('button', { name: '打开通知提醒' }).click()
  const checkRail = async () => {
    const bounds = await page.evaluate(() => {
      const rect = selector => {
        const r = document.querySelector(selector).getBoundingClientRect()
        return { left: r.left, right: r.right, width: r.width }
      }
      return { main: rect('main'), rail: rect('.notification-viewport.open'), bell: rect('.notification-bell'), send: rect('.send-button'), width: innerWidth, scrollWidth: document.documentElement.scrollWidth }
    })
    assert(bounds.main.right <= bounds.rail.left, 'Rail overlaps conversation')
    assert(bounds.bell.right <= bounds.rail.left, 'Bell overlaps rail')
    assert(bounds.send.right <= bounds.rail.left, 'Composer overflows into rail')
    assert(bounds.rail.right <= bounds.width && bounds.scrollWidth <= bounds.width, 'Horizontal window overflow')
    assert(await page.locator('.reminder-bubble').count() === 0, 'Duplicate reminder bubble')
  }
  await checkRail()
  await page.getByRole('textbox', { name: '给 Codex 发送消息' }).click()
  assert(await page.getByRole('complementary', { name: '通知提醒栏' }).isVisible(), 'Typing closed the rail')
  await capture('04-reminder-rail')
  await page.goto(`${base}?scenario=question`)
  const answer = page.getByRole('textbox', { name: '问题 1回答' })
  await answer.fill('使用现有的 Codex Harness Bot')
  const shortHeight = await answer.evaluate(field => field.getBoundingClientRect().height)
  assert(shortHeight <= 40, 'Short answer is taller than one row')
  await capture('03-question-single-line')
  await answer.press('End')
  await answer.press('Shift+Enter')
  await answer.pressSequentially('补充：先支持手机输入和问题回复。')
  assert((await answer.inputValue()).includes('\n'), 'Shift+Enter did not insert a newline')
  const longHeight = await answer.evaluate(field => field.getBoundingClientRect().height)
  assert(longHeight > shortHeight, 'Answer did not grow automatically')
  await capture('03-question-expanded')
  await page.goto(`${base}?theme=light`)
  await page.getByRole('button', { name: '准', exact: true }).click()
  await page.getByRole('button', { name: '打开通知提醒' }).click()
  await checkRail()
  await capture('04-reminder-rail-light')
  await page.goto(`${base}?sidebar=1`)
  await page.setViewportSize({ width: 980, height: 640 })
  await page.getByRole('complementary', { name: '侧栏布局占位' }).waitFor()
  assert(await page.locator('.sidebar').evaluate(sidebar => sidebar.getBoundingClientRect().width) === 284, 'Sidebar placeholder missing')
  assert(await page.locator('.thread-tabs button').count() > 10, 'Missing long tab list')
  await page.getByRole('button', { name: '打开通知提醒' }).click()
  await checkRail()
  assert(await page.getByRole('combobox', { name: '审批模式' }).evaluate(field => field.getBoundingClientRect().width) >= 30, 'Approval selector collapsed')
  await capture('04-narrow-with-sidebar')
}
