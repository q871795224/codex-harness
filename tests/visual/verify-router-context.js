async (page) => {
  const base = 'http://127.0.0.1:1439/tests/visual/router-context.html'
  const checkWidth = async () => {
    if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Router UI overflows the window')
  }
  await page.setViewportSize({ width: 1200, height: 800 })
  await page.goto(base)
  await page.getByRole('heading', { name: '介绍', exact: true }).waitFor()
  await page.getByText('21 小时后检查').waitFor()
  if (await page.getByText('当前状态', { exact: true }).count()) throw new Error('Old status section still exists')
  const positions = await page.evaluate(() => {
    const name = document.querySelector('.router-workspace-heading h3').getBoundingClientRect()
    const path = document.querySelector('.router-workspace-path').getBoundingClientRect()
    const state = document.querySelector('.router-workspace-heading .router-status').getBoundingClientRect()
    const next = document.querySelector('.router-next-check').getBoundingClientRect()
    const button = document.querySelector('.router-detail-actions button').getBoundingClientRect()
    return { sameLine: Math.abs(name.top - path.top) < 10, statusLeft: state.left < name.left, nextLeft: next.right < button.left }
  })
  if (!positions.sameLine || !positions.statusLeft || !positions.nextLeft) throw new Error('Detail layout does not match the compact spec')
  await checkWidth()
  await page.screenshot({ path: 'docs/review/workspace-router/compact-workspaces-dark.png', fullPage: true })
  await page.getByRole('button', { name: '立即更新', exact: true }).click()
  await page.getByText('检查完成，最新状态已显示。').waitFor()
  await page.getByText('24 小时后检查').waitFor()
  await page.setViewportSize({ width: 1200, height: 1150 })
  await page.getByRole('tab', { name: '设置', exact: true }).click()
  if (await page.getByRole('radio', { name: 'Jev / Laya' }).isEnabled()) throw new Error('Laya must remain unavailable')
  if (await page.getByRole('radio', { name: '其他模型 API' }).isEnabled()) throw new Error('Other APIs must remain unavailable')
  await page.getByRole('spinbutton', { name: '纠错引用上限' }).fill('5')
  await page.getByRole('combobox', { name: '纠错选取规则' }).selectOption('recent')
  await page.getByRole('button', { name: '保存设置' }).click()
  await page.getByText('已保存，下次路由生效').waitFor()
  await page.screenshot({ path: 'docs/review/workspace-router/compact-settings-dark.png', fullPage: true })
  await page.getByRole('tab', { name: '最终 Prompt' }).click()
  await page.getByRole('textbox', { name: 'Prompt 预览用户输入' }).fill('请查 DNS API 内存，并优化 Harness 的工作区路由')
  await page.getByRole('button', { name: '按已保存设置生成' }).click()
  await page.locator('pre[aria-label="最终 Prompt"]').waitFor()
  const prepared = await page.locator('pre[aria-label="最终 Prompt"]').innerText()
  if (!prepared.includes('developerInstructions') || !prepared.includes('input[1]') || !prepared.includes('outputSchema')) throw new Error('Missing actual prompt fields')
  if (!prepared.includes('corrections')) throw new Error('Feedback examples missing')
  await page.screenshot({ path: 'docs/review/workspace-router/compact-prompt-dark.png', fullPage: true })
  await page.getByRole('tab', { name: '反馈', exact: true }).click()
  await page.getByText('看一下 DNS API 在 AI Cloud 里的内存占用情况。', { exact: true }).waitFor()
  await page.screenshot({ path: 'docs/review/workspace-router/compact-feedback-dark.png', fullPage: true })
  await page.setViewportSize({ width: 640, height: 1050 })
  await page.goto(base + '?theme=light')
  await page.getByRole('heading', { name: '介绍', exact: true }).waitFor()
  await checkWidth()
  await page.screenshot({ path: 'docs/review/workspace-router/compact-workspaces-light-narrow.png', fullPage: true })
}
